"""Derive the TA-Lib-equivalent catalogue by interrogating the oracle.

    python scripts/catalogue/talib_catalogue.py --write     # refresh the doc
    python scripts/catalogue/talib_catalogue.py --check     # fail if it drifted

Every fact here comes from running ta-lib-python, not from reading TA-Lib's
source: names, groups, parameter defaults and output names from
``talib.abstract``, and the accepted range of each integer parameter by
bisecting the real library until it answers TA_BAD_PARAM. That keeps the
catalogue reproducible from the pinned dev dependency alone, and it is the same
rule the golden files follow (``docs/TESTING.md`` section 2): behaviour is
defined by what the oracle does, not by what a document says it does.

What this does *not* take from TA-Lib is any algorithm. Implementations are
written from published formulas and checked against the oracle
(``docs/CONVENTIONS.md`` section 4).
"""

